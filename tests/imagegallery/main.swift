import Foundation

var gallery = ImageGallerySelection(ids: ["a", "b", "a", "", "c"], selected: "b")
precondition(gallery.ids == ["a", "b", "c"] && gallery.index == 1)
gallery.step(1)
precondition(gallery.selected == "c")
gallery.step(1)
precondition(gallery.selected == "c", "last page does not wrap unexpectedly")
gallery.step(Int.min)
precondition(gallery.selected == "a")
gallery.step(Int.max)
precondition(gallery.selected == "c", "invalid deltas cannot overflow")
gallery.select("not-in-this-message")
precondition(gallery.selected == "c", "cannot select a foreign path")
gallery.select("a")
precondition(gallery.index == 0)
let fallback = ImageGallerySelection(ids: ["first", "last"], selected: "missing")
precondition(fallback.selected == "first")
var empty = ImageGallerySelection(ids: [], selected: "missing")
empty.step(1)
precondition(empty.selected.isEmpty && empty.ids.isEmpty)
print("IMAGE_GALLERY_PASS selection/deduplication/bounds; UIKit gestures and image decoding require device")
